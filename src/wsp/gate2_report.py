"""Gate 2 numbers from saved artifacts only -> wsp_runs/gate2/{gate2_numbers.json, GATE2_TABLES.md}.

Held-out result = iter_val_1..3 POOLED (never used for any choice), paired vs θ_qa per item.
Also summarises Gate 2a (the document-count-confounded first run, preserved in
wsp_runs/gate2a_doccount_confounded/) so the shortcut finding is reproducible from disk.

    python -m wsp.gate2_report
"""
from __future__ import annotations

import json

import numpy as np

from . import config_wsp as C, metrics, paths
from .loop_eval import discrimination

G = paths.RUNS / "gate2"
G2A = paths.RUNS / "gate2a_doccount_confounded"
FOLDS = (1, 2, 3)
ABS, ANS = C.ABS_KINDS, C.ANS_KINDS


def _log(d=G):
    return [json.loads(l) for l in open(d / "log.jsonl", encoding="utf-8")]


def _per(name):
    out = {}
    for f in FOLDS:
        p = (G / f"baseline_qa_iter_val_{f}.json") if name == "qa" else (G / "reports" / f"{name}__iter_val_{f}.json")
        for it in json.loads(p.read_text())["per_item"]:
            out[it["id"]] = it
    return out


def _pd(a, b, kinds, m):
    kinds = (kinds,) if isinstance(kinds, str) else kinds
    return metrics.paired_delta_ci({k: v["scores"][m] for k, v in a.items() if v["kind"] in kinds},
                                   {k: v["scores"][m] for k, v in b.items() if v["kind"] in kinds})


def _lvl(a, kinds, m):
    kinds = (kinds,) if isinstance(kinds, str) else kinds
    return metrics.bootstrap_ci(v["scores"][m] for v in a.values() if v["kind"] in kinds)


def _fmt(d):
    return f"{d['delta']:+.3f} [{d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}]{' ✓' if d['significant'] else ''}"


def main():
    log = _log()
    sels = [r for r in log if r["kind"] == "selection"]; sel = sels[-1]
    chosen = sel["chosen"]
    arms = ["qa", chosen] + [f"random_s{s}" for s in range(3)]
    base = _per("qa")
    num = {"selection": sels, "train": [r for r in log if r["kind"] == "train"],
           "dev_fold0": [r for r in log if r["kind"] == "eval" and r["split"] == "iter_val_0"], "heldout": {}}
    md = ["# Gate 2 — computed tables", "", "_Generated by `python -m wsp.gate2_report` from saved artifacts._", ""]

    # ---- Gate 2a: the confounded run ----
    sp = G2A / "shortcut_probe.json"
    if sp.exists():
        r = json.loads(sp.read_text())
        md += ["## Gate 2a (superseded): document-count shortcut", "",
               "First run, item pool v1, where document count identified the condition (as in the frozen eval and raft.jsonl). "
               "Abstention rate on held-out items, filled 2×3 grid:", "",
               "| arm | answerable 1 / 2 / 3 docs | absent 1 / 2 / 3 docs |", "|---|---|---|"]
        for a, v in r.items():
            c = v["cells"]
            md.append(f"| {a} | " + " / ".join(f"{c[k]['abstain'][0]:.3f}" for k in ("ans1", "ans2", "ans3")) +
                      " | " + " / ".join(f"{c[k]['abstain'][0]:.3f}" for k in ("abs1", "abs2", "abs3")) + " |")
        md.append("")

    # ---- dev fold ----
    md += [f"## Gate 2 (pool v2, document count decorrelated). Dev fold iter_val_0, used for selection only", "",
           f"Selected: **{chosen}** (rule: largest abstention gain among configs passing safety + all approved guardrails; "
           f"passing configs: {sel.get('passing') or 'none — this arm FAILS the guardrails and is reported for the record only'})", "",
           "| arm | ‖Δθ‖/‖θ‖ | abstain Δ (abs1–3) | discrimination k=1/2/3 | clean F1 Δ (ans1) | false-abstain Δ (ans1–3) | retention sec / case-law / web | guardrails |",
           "|---|---|---|---|---|---|---|---|"]
    for r in num["dev_fold0"]:
        c = r["compare"]; rt = c.get("retention", {}); ds = {int(k) if k != "min" else k: v for k, v in c["discrimination"].items()}
        fails = [k for k, v in c["guardrails"].items() if not v]
        md.append(f"| {r['arm']} | {r['norms']:.4f} | {_fmt(c['target_abstain'])} | {ds[1]:+.3f} / {ds[2]:+.3f} / {ds[3]:+.3f} | "
                  f"{_fmt(c['ans1.token_f1'])} | {_fmt(c['ans_all.false_abstain'])} | "
                  + " / ".join(f"{100 * rt[s]['rel']:+.2f}%" for s in ("sec", "case-law", "fineweb-edu") if s in rt)
                  + f" | {'PASS' if not fails else 'FAIL: ' + ', '.join(fails)} |")

    # ---- held-out ----
    md += ["", "## Held-out folds 1–3 pooled (never used for any choice), paired vs θ_qa", ""]
    md.append("Items per kind: " + ", ".join(f"{k} {sum(1 for v in base.values() if v['kind'] == k)}" for k in ANS + ABS))
    md += ["", "| arm | abstain rate abs1 / abs2 / abs3 | abstain rate ans1 / ans2 / ans3 | discrimination min | clean F1 (ans1) | F1 ans1–3 | clean fabrication |",
           "|---|---|---|---|---|---|---|"]
    for a in arms:
        try:
            p = _per(a)
        except FileNotFoundError:
            md.append(f"| {a} | (missing — vetoed?) ||||||"); continue
        rep = {"per_item": list(p.values())}
        row = {"abstain_levels": {k: _lvl(p, k, "abstain") for k in ABS + ANS},
               "discrimination": discrimination(rep),
               "f1_ans1": _lvl(p, "ans1", "token_f1"), "f1_ans": _lvl(p, ANS, "token_f1"),
               "fab_ans1": _lvl(p, "ans1", "fabrication")}
        if a != "qa":
            row["paired"] = {"target_abstain": _pd(p, base, ABS, "abstain"), "ans1_f1": _pd(p, base, "ans1", "token_f1"),
                             "ans_f1": _pd(p, base, ANS, "token_f1"), "ans_false_abstain": _pd(p, base, ANS, "false_abstain"),
                             "ans1_fab": _pd(p, base, "ans1", "fabrication")}
            row["guardrails"] = {"clean_f1": row["paired"]["ans1_f1"]["ci"][0] >= C.CLEAN_F1_MIN_DELTA_LOWER_CI,
                                 "fabrication": not (row["paired"]["ans1_fab"]["significant"] and row["paired"]["ans1_fab"]["delta"] > 0)}
        num["heldout"][a] = row
        L = row["abstain_levels"]
        md.append(f"| {a} | " + " / ".join(f"{L[k][0]:.3f}" for k in ABS) + " | " + " / ".join(f"{L[k][0]:.3f}" for k in ANS) +
                  f" | {row['discrimination']['min']:+.3f} | {row['f1_ans1'][0]:.3f} | {row['f1_ans'][0]:.3f} | {row['fab_ans1'][0]:.3f} |")
    md += ["", "Paired deltas vs θ_qa (held-out):", "", "| arm | abstain Δ (target) | clean F1 Δ | F1 Δ ans1–3 | false-abstain Δ | clean fabrication Δ | guardrails (F1, fab) |",
           "|---|---|---|---|---|---|---|"]
    for a in arms[1:]:
        if a not in num["heldout"]:
            continue
        P = num["heldout"][a]["paired"]; g = num["heldout"][a]["guardrails"]
        md.append(f"| {a} | {_fmt(P['target_abstain'])} | {_fmt(P['ans1_f1'])} | {_fmt(P['ans_f1'])} | {_fmt(P['ans_false_abstain'])} | "
                  f"{_fmt(P['ans1_fab'])} | {'PASS' if all(g.values()) else 'FAIL'} |")
    if chosen in num["heldout"]:
        lp = _per(chosen)
        tv = []
        for s in range(3):
            if f"random_s{s}" in num["heldout"]:
                tv.append(_pd(lp, _per(f"random_s{s}"), ABS, "abstain"))
        num["heldout"]["targeted_minus_random"] = tv
        md += ["", "Targeted (LoRA) − random, abstention on abs1–3, same items: " + "; ".join(f"s{i}: {_fmt(d)}" for i, d in enumerate(tv))]

    # ---- milestones ----
    ms = [r for r in log if r["kind"] == "milestone"]
    if ms:
        keys = list(ms[0]["retention"])
        q = {s: np.load(paths.RUNS / "gate1" / "retention" / f"qa__{s.replace('/', '__')}.npy").mean() for s in keys}
        md += ["", "## Milestone checks: full held-out retention (all windows) and Phase-0 copy probe", "",
               "| arm | " + " | ".join(keys) + " | verbatim copy (≥ 0.93) |", "|---|" + "---|" * (len(keys) + 1)]
        for r in ms:
            vc = r["probes"]["C_needle_verbatim"]
            md.append(f"| {r['arm']} | " + " | ".join(f"{100 * (r['retention'][s]['loss'] / q[s] - 1):+.2f}%" for s in keys) +
                      f" | {vc['rate']:.3f} {[round(x, 3) for x in vc['ci95']]} {'PASS' if vc['rate'] >= C.VERBATIM_COPY_MIN else 'FAIL'} |")
        num["milestones"] = ms
    (G / "gate2_numbers.json").write_text(json.dumps(num, indent=1, default=float))
    (G / "GATE2_TABLES.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
