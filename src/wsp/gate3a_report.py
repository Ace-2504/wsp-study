"""Gate 3a tables from saved artifacts -> wsp_runs/gate3a/{GATE3A_TABLES.md, gate3a_numbers.json}.

    python -m wsp.gate3a_report
"""
from __future__ import annotations

import json

import numpy as np

from . import paths

G3 = paths.RUNS / "gate3a"
G2 = paths.RUNS / "gate2"
DOMS = ("sec", "case-law", "fineweb-edu")


def _g2_full(lr):
    """Gate 2's scale-1.0 dev-fold record for a LoRA, in the same shape as a Gate 3a record."""
    for l in open(G2 / "log.jsonl", encoding="utf-8"):
        r = json.loads(l)
        if r["kind"] == "eval" and r["arm"] == f"lora_lr{lr}" and r["split"] == "iter_val_0":
            return {"arm": f"gate2 lora_lr{lr} (s=1)", "norm": r["norms"], "compare": r["compare"],
                    "meta": {"phase": "A", "lr": lr, "scale": 1.0}}


def _row(r):
    c = r["compare"]; ds = c["discrimination"]; rt = c["retention"]
    fails = [k for k, v in c["guardrails"].items() if not v]
    g = c["target_abstain"]["delta"]
    valid = g > 0 and ds["min"] is not None and ds["min"] >= 0.5 * g
    return (f"| {r['arm']} | {r['norm']:.4f} | {g:+.3f} | {ds['min']:+.3f} | {c['ans1.token_f1']['delta']:+.3f} | "
            f"{c['ans_all.false_abstain']['delta']:+.3f} | " + " / ".join(f"{100 * rt[d]['rel']:+.2f}%" for d in DOMS) +
            f" | {'pass' if not fails else 'FAIL ' + ','.join(fails)} | {'yes' if valid else 'no'} |")


def main():
    res = json.loads((G3 / "results.json").read_text())
    dev = {k[:-len("__iter_val_0")]: v for k, v in res.items() if k.endswith("__iter_val_0")}
    head = ["| config | ‖Δθ‖/‖θ‖ | abstain Δ | discrimination min | clean F1 Δ | false-abstain Δ | retention sec / case-law / web | guardrails | valid |",
            "|---|---|---|---|---|---|---|---|---|"]
    md = ["# Gate 3a — computed tables", "", "_Generated by `python -m wsp.gate3a_report` from saved artifacts. Dev fold iter_val_0._", ""]
    num = {"dev": dev}
    for lr in ("0.0001", "0.0003"):
        rows = sorted([v for v in dev.values() if v["meta"].get("phase") == "A" and v["meta"]["lr"] == lr],
                      key=lambda v: v["meta"]["scale"]) + [_g2_full(lr)]
        md += [f"## Phase A — scale sweep, LoRA lr {lr}", ""] + head + [_row(r) for r in rows] + [""]
        s = np.array([r["meta"]["scale"] for r in rows])
        y = np.array([100 * np.mean([r["compare"]["retention"][d]["rel"] for d in DOMS]) for r in rows])
        (a, b), *_ = np.linalg.lstsq(np.stack([s, s ** 2], 1), y, rcond=None)
        smax = (-a + np.sqrt(a * a + 4 * b * 0.5)) / (2 * b)
        num[f"retention_fit_lr{lr}"] = {"a_linear": a, "b_quadratic": b, "scale_at_0.5pct": smax,
                                        "points": list(zip(s.tolist(), y.tolist()))}
        md += [f"Mean retention cost fits {a:.2f}·s + {b:.2f}·s² (%), so the +0.5% budget is reached at s ≈ {smax:.3f}.", ""]
    md += ["## Phase B — attribution (lr 3e-4 delta, one group at a time, scale 1.0)", ""] + head + \
          [_row(v) for k, v in dev.items() if v["meta"].get("phase") == "B"] + [""]
    rk = [json.loads(l) for l in open(G3 / "log.jsonl", encoding="utf-8")]
    rank = next((r["ranking"] for r in rk if r["kind"] == "phaseB_ranking"), [])
    md += ["Groups with a significant abstention gain, by efficiency (abstain Δ / mean retention %): " +
           (", ".join(f"{'_'.join(x['group'])} {x['efficiency']:.2f}" for x in rank) or "none"), ""]
    md += ["## Phase C — efficient subsets", ""] + head + [_row(v) for k, v in dev.items() if v["meta"].get("phase") == "C"] + [""]
    sel = [r for r in rk if r["kind"] == "selection"]
    md += [f"**Selection:** {sel[-1].get('chosen') if sel else 'n/a'} — {sel[-1].get('reason', '') if sel else ''}", ""]
    dp = G3 / "diagnostic_abstain_logprob.json"
    if dp.exists():
        d = json.loads(dp.read_text()); num["diagnostic"] = d
        md += ["## Post-hoc diagnostic (exploratory, not pre-registered): teacher-forced abstention signal", "",
               f"Score = log P(\"{d['target']}<|eos|>\" | prompt). AUROC separates absent from answerable items at the same document count.", "",
               "| scale of Δ_lr3e-4 | AUROC k=1 / 2 / 3 | AUROC pooled | mean log P, absent | mean log P, answerable |", "|---|---|---|---|---|"]
        for s, r in d["results"].items():
            md.append(f"| {s} | " + " / ".join(f"{r['auroc_k'][k]:.3f}" for k in ("1", "2", "3")) +
                      f" | {r['auroc_pooled']:.3f} | {r['mean_logp_absent']:.2f} | {r['mean_logp_answerable']:.2f} |")
    (G3 / "gate3a_numbers.json").write_text(json.dumps(num, indent=1, default=float))
    (G3 / "GATE3A_TABLES.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
